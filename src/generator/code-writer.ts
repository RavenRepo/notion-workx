import Handlebars from "handlebars";
import { readFileSync } from "node:fs";
import path from "node:path";
import { GeneratorOutput, ToolDefinition, ToolParam, WorxConfig } from "../types";

export interface WriterOutput {
  indexTs: string;
  envExample: string;
  worxConfig: string;
  readmeMd: string;
}

export function writeCode(output: GeneratorOutput, config: WorxConfig): WriterOutput {
  return {
    indexTs: writeIndexTs(output),
    envExample: writeEnvExample(output),
    worxConfig: writeWorxConfig(output, config),
    readmeMd: writeReadme(output, config),
  };
}

function writeIndexTs(output: GeneratorOutput): string {
  const blocks = output.tools.map(writeToolBlock).join("\n\n");
  return `// Generated by WorX - do not edit manually.
// Source: ${output.apiTitle} v${output.apiVersion}
import { Worker, j } from "@notionhq/workers";

const worker = new Worker();

const BASE_URL = ${JSON.stringify(output.baseUrl)};

function requireSecret(name: string): string {
  const value = process.env[name];
  if (!value) {
    throw new Error(\`Missing required secret: \${name}\`);
  }
  return value;
}

${blocks}

export default worker;
`;
}

function writeToolBlock(tool: ToolDefinition): string {
  const schemaFields = tool.params.map(writeSchemaField).join("\n");
  const paramNames = tool.params.map((param) => param.name);
  const executeInput =
    paramNames.length > 0 ? `{ ${paramNames.join(", ")} }` : "_input";
  const urlBlock = writeUrlBlock(tool);
  const headersBlock = writeHeadersBlock(tool);
  const bodyBlock = writeBodyBlock(tool);
  const fetchBlock = writeFetchBlock(tool, Boolean(bodyBlock));
  const commentLines = [
    "/**",
    ` * ${tool.title}`,
    ` * ${tool.description}`,
    ...(tool.deprecated ? [" * @deprecated This endpoint is marked deprecated in the spec."] : []),
    " */",
  ].join("\n");

  return `${commentLines}
worker.tool(${JSON.stringify(tool.name)}, {
  title: ${JSON.stringify(tool.title)},
  description: ${JSON.stringify(tool.description)},
  schema: j.object({
${schemaFields || "    // No parameters defined"}
  }),
  execute: async (${executeInput}) => {
${indent(urlBlock, 4)}
${indent(headersBlock, 4)}
${bodyBlock ? `${indent(bodyBlock, 4)}\n` : ""}${indent(fetchBlock, 4)}
    if (!res.ok) {
      const error = await res.text().catch(() => res.statusText);
      throw new Error(\`${tool.name} failed with status \${res.status}: \${error}\`);
    }
    return res.json();
  },
});`;
}

function writeSchemaField(param: ToolParam): string {
  const expression = `${jType(param)}.describe(${JSON.stringify(paramDescription(param))})`;
  return `    ${param.name}: ${expression},`;
}

function jType(param: ToolParam): string {
  if (param.type === "string") {
    return "j.string()";
  }
  if (param.type === "number") {
    return "j.number()";
  }
  if (param.type === "boolean") {
    return "j.boolean()";
  }
  if (param.type === "array") {
    switch (param.itemType) {
      case "number":
        return "j.array(j.number())";
      case "boolean":
        return "j.array(j.boolean())";
      case "object":
        return "j.array(j.string())";
      default:
        return "j.array(j.string())";
    }
  }
  return "j.string()";
}

function paramDescription(param: ToolParam): string {
  if (param.type === "array" && param.itemType === "object") {
    return `${param.description} JSON string per item.`;
  }
  if (param.type === "object") {
    return `${param.description} JSON object as string.`;
  }
  return param.description;
}

function writeUrlBlock(tool: ToolDefinition): string {
  const pathParams = tool.params.filter((param) => param.location === "path");
  const queryParams = tool.params.filter((param) => param.location === "query");
  const replacementLines = pathParams
    .map((param) => `  .replace(${JSON.stringify(`{${param.originalName}}`)}, String(${param.name}))`)
    .join("\n");
  const urlLine =
    replacementLines.length > 0
      ? `const url = new URL(\`${"${BASE_URL}"}${tool.pathTemplate}\`\n${replacementLines}\n);`
      : `const url = new URL(\`${"${BASE_URL}"}${tool.pathTemplate}\`);`;
  const queryLines = queryParams
    .map((param) =>
      param.required
        ? `url.searchParams.set(${JSON.stringify(param.originalName)}, String(${param.name}));`
        : `if (${param.name} !== undefined) url.searchParams.set(${JSON.stringify(
            param.originalName,
          )}, String(${param.name}));`,
    )
    .join("\n");

  return [urlLine, queryLines].filter(Boolean).join("\n");
}

function writeHeadersBlock(tool: ToolDefinition): string {
  const lines = ['const headers: Record<string, string> = {'];
  if (tool.auth.type === "bearer") {
    lines.push(`  "Authorization": \`Bearer \${requireSecret(${JSON.stringify(tool.auth.secretName)})}\`,`);
  } else if (tool.auth.type === "apikey_header" && tool.auth.headerName) {
    lines.push(
      `  ${JSON.stringify(tool.auth.headerName)}: requireSecret(${JSON.stringify(tool.auth.secretName)}),`,
    );
  } else if (tool.auth.type === "unsupported") {
    lines.push(`  "Authorization": \`Bearer \${requireSecret(${JSON.stringify(tool.auth.secretName)})}\`,`);
  }
  lines.push('  "Content-Type": "application/json",');
  lines.push("};");

  const postHeaderLines = tool.params
    .filter((param) => param.location === "header")
    .map((param) =>
      param.required
        ? `headers[${JSON.stringify(param.originalName)}] = String(${param.name});`
        : `if (${param.name} !== undefined) headers[${JSON.stringify(param.originalName)}] = String(${param.name});`,
    );

  if (tool.auth.type === "apikey_query" && tool.auth.queryParamName) {
    postHeaderLines.unshift(
      `url.searchParams.set(${JSON.stringify(tool.auth.queryParamName)}, requireSecret(${JSON.stringify(
        tool.auth.secretName,
      )}));`,
    );
  }

  return [lines.join("\n"), ...postHeaderLines].join("\n");
}

function writeBodyBlock(tool: ToolDefinition): string {
  if (!["POST", "PUT", "PATCH"].includes(tool.method)) {
    return "";
  }

  const bodyParams = tool.params.filter((param) => param.location === "body");
  if (bodyParams.length === 0) {
    return "";
  }

  const entries = bodyParams.map((param) =>
    param.required
      ? `${JSON.stringify(param.originalName)}: ${param.name},`
      : `...(${param.name} !== undefined ? { ${JSON.stringify(param.originalName)}: ${param.name} } : {}),`,
  );

  return `const body = JSON.stringify({
${entries.map((entry) => `  ${entry}`).join("\n")}
});`;
}

function writeFetchBlock(tool: ToolDefinition, hasBody: boolean): string {
  const lines = [
    "const res = await fetch(url.toString(), {",
    `  method: ${JSON.stringify(tool.method)},`,
    "  headers,",
  ];
  if (hasBody) {
    lines.push("  body,");
  }
  lines.push("});");
  return lines.join("\n");
}

function writeEnvExample(output: GeneratorOutput): string {
  const lines = [
    `# WorX generated - ${output.apiTitle} v${output.apiVersion}`,
    "# Copy to .env and fill in your values",
    "",
  ];

  if (output.auth.secretName) {
    lines.push(`${output.auth.secretName}=your_${output.auth.secretName.toLowerCase()}_here`, "");
  }

  lines.push("# Base URL (update if needed)", `# WORX_BASE_URL=${output.baseUrl}`, "");
  return lines.join("\n");
}

function writeWorxConfig(output: GeneratorOutput, config: WorxConfig): string {
  return `${JSON.stringify(
    {
      generatedAt: new Date().toISOString(),
      specSource: config.specUrl ?? config.specFile ?? "",
      apiTitle: output.apiTitle,
      apiVersion: output.apiVersion,
      toolCount: output.tools.length,
      skippedCount: output.skipped.length,
      auth: output.auth,
      filter: config.filter ?? [],
      skippedEndpoints: output.skipped.map(({ method, path: endpointPath, reason }) => ({
        method,
        path: endpointPath,
        reason,
      })),
    },
    null,
    2,
  )}\n`;
}

function writeReadme(output: GeneratorOutput, config: WorxConfig): string {
  const templatePath = path.resolve(__dirname, "templates", "readme.hbs");
  const template = Handlebars.compile(readFileSync(templatePath, "utf8"), { noEscape: true });
  return `${template({
    ...output,
    toolCount: output.tools.length,
    skippedCount: output.skipped.length,
    specSource: config.specUrl ?? config.specFile ?? "",
  }).trim()}\n`;
}

function indent(value: string, spaces: number): string {
  const prefix = " ".repeat(spaces);
  return value
    .split("\n")
    .map((line) => (line.length > 0 ? `${prefix}${line}` : line))
    .join("\n");
}
