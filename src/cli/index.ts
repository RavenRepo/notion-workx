#!/usr/bin/env node

import { Command } from "commander";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { deployWorker } from "../deploy/ntn";
import { detectAuth } from "../generator/auth-detector";
import { writeCode, WriterOutput } from "../generator/code-writer";
import { buildTools } from "../generator/tool-builder";
import { loadSpec } from "../parser/openapi";
import { EndpointResult, GeneratorOutput, ToolDefinition, WorxConfig } from "../types";

interface GenerateOptions {
  spec: string;
  output: string;
  filter?: string[];
  dryRun: boolean;
  deploy: boolean;
}

const program = new Command();

program
  .name("worx")
  .description("Generate Notion Worker tools from OpenAPI specs")
  .version("1.0.0");

program
  .command("generate")
  .description("Generate a Notion Worker from an OpenAPI spec")
  .requiredOption("--spec <url|path>", "OpenAPI 3.x spec URL or file path")
  .option("--output <dir>", "Output directory for generated Worker", "./worx-output")
  .option("--filter <tags...>", "Only generate tools for these OAS tags")
  .option("--dry-run", "Print what would be generated without writing files", false)
  .option("--deploy", "Run ntn workers deploy after generating", false)
  .action(async (options: GenerateOptions) => {
    await generate(options);
  });

program.parseAsync(process.argv).catch((error: unknown) => {
  const message = error instanceof Error ? error.message : "Unknown CLI error";
  console.error(red(`Error: ${message}`));
  process.exitCode = 1;
});

async function generate(options: GenerateOptions): Promise<void> {
  console.log(`WorX v1.0 · Generating Worker from ${options.spec}`);

  const outputDir = path.resolve(options.output);
  const config: WorxConfig = {
    specUrl: isHttpUrl(options.spec) ? options.spec : undefined,
    specFile: isHttpUrl(options.spec) ? undefined : options.spec,
    outputDir,
    filter: options.filter ?? [],
    dryRun: Boolean(options.dryRun),
    groupByTag: false,
  };

  const spec = await loadSpec(options.spec);
  const pathCount = Object.keys(spec.paths ?? {}).length;
  console.log(`✓ Spec loaded: ${spec.info.title} v${spec.info.version} - ${pathCount} paths`);

  const auth = detectAuth(spec);
  console.log(`✓ Auth: ${auth.type}${auth.secretName ? ` (${auth.secretName})` : ""}`);

  const endpointResults = buildTools(spec, config, auth);
  const tools = endpointResults.filter(isToolDefinition);
  const skipped = endpointResults.filter(isSkippedEndpoint);
  console.log(`✓ Endpoints analyzed: ${tools.length} tools, ${skipped.length} skipped`);
  for (const endpoint of skipped) {
    console.warn(yellow(`  - ${endpoint.method} ${endpoint.path}: ${endpoint.reason}`));
  }

  const generatorOutput: GeneratorOutput = {
    tools,
    skipped,
    auth,
    baseUrl: spec.servers[0]?.url ?? "https://api.example.com",
    apiTitle: spec.info.title,
    apiVersion: spec.info.version,
  };
  const workerName = generatedWorkerName(spec.info.title);
  const writerOutput = writeCode(generatorOutput, config);
  const files = generatedFiles(writerOutput, spec.info.title, workerName);

  if (config.dryRun) {
    for (const file of files) {
      console.log(`${file.path}: ${lineCount(file.content)} lines`);
    }
    console.log("Dry run complete. No files written.");
    return;
  }

  await mkdir(path.join(outputDir, "src"), { recursive: true });
  for (const file of files) {
    const targetPath = path.join(outputDir, file.path);
    await writeFile(targetPath, file.content, "utf8");
    console.log(`✓ Written: ${targetPath}`);
  }

  if (options.deploy) {
    const result = await deployWorker(outputDir, workerName);
    console.log(result);
  }

  console.log(`
✓ Done! ${tools.length} tools generated in ${outputDir}

Next steps:
  1. cd ${outputDir}
  2. cp .env.example .env${auth.secretName ? `  (fill in ${auth.secretName})` : ""}
  3. npm install
  4. npm install -g ntn  (if ntn is not already available)
  5. ntn workers deploy --name ${workerName}
  ${auth.secretName ? "6. ntn workers env push --yes" : "6. Future updates: ntn workers deploy"}
`);
}

function generatedFiles(
  writerOutput: WriterOutput,
  apiTitle: string,
  workerName: string,
): Array<{ path: string; content: string }> {
  return [
    { path: "src/index.ts", content: writerOutput.indexTs },
    { path: ".env.example", content: writerOutput.envExample },
    { path: "worx.config.json", content: writerOutput.worxConfig },
    { path: "README.md", content: writerOutput.readmeMd },
    { path: "package.json", content: generatedPackageJson(apiTitle, workerName) },
    { path: "tsconfig.json", content: generatedTsConfig() },
  ];
}

function generatedPackageJson(apiTitle: string, workerName: string): string {
  return `${JSON.stringify(
    {
      name: workerName,
      version: "0.1.0",
      description: `Notion Worker for ${apiTitle} - generated by WorX`,
      type: "module",
      main: "src/index.ts",
      engines: {
        node: ">=22.0.0",
      },
      scripts: {
        build: "tsc",
        deploy: "ntn workers deploy --no-git",
        "deploy:create": `ntn workers deploy --name ${workerName} --no-git`,
        "env:push": "ntn workers env push --yes",
        typecheck: "tsc --noEmit",
      },
      dependencies: {
        "@notionhq/workers": "latest",
      },
      devDependencies: {
        "@types/node": "^24.0.0",
        typescript: "^5.0.0",
      },
    },
    null,
    2,
  )}\n`;
}

function generatedWorkerName(apiTitle: string): string {
  return `${toKebabCase(apiTitle)}-worker`;
}

function generatedTsConfig(): string {
  return `${JSON.stringify(
    {
      compilerOptions: {
        target: "ES2022",
        module: "ESNext",
        moduleResolution: "bundler",
        strict: true,
        skipLibCheck: true,
        outDir: "dist",
      },
      include: ["src/**/*"],
    },
    null,
    2,
  )}\n`;
}

function isToolDefinition(result: EndpointResult): result is ToolDefinition {
  return result.skipped === false;
}

function isSkippedEndpoint(result: EndpointResult): result is EndpointResult & { skipped: true } {
  return result.skipped === true;
}

function lineCount(value: string): number {
  return value.trimEnd().split("\n").length;
}

function toKebabCase(value: string): string {
  return (
    value
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "api"
  );
}

function isHttpUrl(value: string): boolean {
  return value.startsWith("http://") || value.startsWith("https://");
}

function red(value: string): string {
  return `\u001b[31m${value}\u001b[0m`;
}

function yellow(value: string): string {
  return `\u001b[33m${value}\u001b[0m`;
}
